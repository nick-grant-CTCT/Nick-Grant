def jpeg_bytes() -> bytes:
    im = Image.open(PNG).convert("RGB")
    im = im.resize((1280, 720), Image.Resampling.LANCZOS)
    buf = BytesIO()
    im.save(buf, format="JPEG", quality=42, optimize=True, progressive=False)
    JPEG.write_bytes(buf.getvalue())
    return buf.getvalue()


